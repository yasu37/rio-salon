        <p class="q_ttl">鍼灸による、内側からの美と健康づくりとは？</p>
        <p class="answer">東洋医学に基づいた鍼灸治療と、美容を専門とするエステティックの技術を組み合わせてご提案しています。お一人お一人の体質やお悩みに合わせて、内側からのお手入れをサポートし、心身ともに軽やかに過ごせる毎日を目指します。</p>
      </li>
      <li>
        <p class="q_ttl">美容鍼灸にはどんな効果がありますか?</p>
        <p class="answer">美容鍼灸は、顔まわりの筋肉や巡りに着目した施術です。すっきりとした印象やハリ感、透明感を目指す方に選ばれています。感じ方には個人差があり、施術後の変化をお約束するものではありません。また、肩こりや冷え、頭痛など身体のお悩みに合わせた施術もご相談いただけます。</p>
      </li>
      <li>
        <p class="q_ttl">鍼は痛くないですか?</p>
        <p class="answer">使用する鍼は髪の毛ほど細いものですが、部位やその日の体調によって刺激を感じる場合があります。使い捨ての鍼を使用しており、衛生面にも配慮しております。</p>
      </li>
      <li>
        <p class="q_ttl">美容鍼灸は男性も受けられますか？</p>
        <p class="answer">もちろんお受けいただけます。お顔への美容鍼施術はもちろん、肩こりや腰痛など気になる症状のケアにもご利用いただけます。感じ方には個人差がございますので、体調に合わせてご相談ください。</p>
      </li>
      <li>
        <p class="q_ttl">美容鍼灸はどれくらいのペースで通えばいいですか？</p>
        <p class="answer">お顔や身体の状態を良い状態に保っていただくため、特に通い始めの時期は1～2週間に1回程度のペースをおすすめしております。その後はご様子に合わせて間隔を調整いただけます。</p>
      </li>
      <li>
        <p class="q_ttl">鍼の施術後に気をつけることはありますか?</p>
        <p class="answer">施術後に内出血や赤み、眠気、だるさなどが生じる場合があります。感じ方や経過には個人差がありますので、体調がすぐれない場合はご自宅でゆっくりお過ごしください。ご不安な点は施術前にお気軽にご相談ください。</p>
      </li>
    </ul>
